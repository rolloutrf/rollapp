function planItemsMarkdown(items) {
  return items.map((item) => [
    `### ${item.title}`,
    item.summary,
    `### ${item.approachTitle}`,
    ...item.approach.map((entry) => `- ${entry}`),
    "### Что мне с этим делать",
    ...item.actions.map((entry) => `- ${entry}`),
  ].join("\n\n")).join("\n\n");
}

