import assert from "node:assert/strict";

export async function checkTextBlockSelection(browser, origin) {
  const source = "Первый\n\n**Второй**\n\nТретий\n\nЧетвёртый";
  for (const [width, height] of [[320,844],[390,844],[390,400],[768,844],[820,844],[1024,844],[1440,844],[1920,844]]) {
    const page = await browser.newPage({ viewport: { width, height } });
    const errors = [];
    page.on("pageerror", error => errors.push(error.message));
    page.on("console", message => { if (message.type() === "error" && message.text().includes("ResizeObserver loop")) errors.push(message.text()); });
    await page.route("**/api/**", route => { errors.push("Unexpected API request"); return route.abort(); });
    await page.addInitScript(value => { window.inlineFixtureSource = value; }, source);
    await page.goto(`${origin}/__text-edit?block-selection=1`);
    const editor = page.getByRole("textbox", { name: "О себе", exact: true });
    const selected = editor.locator(".inline-editor__block-selected");
    const texts = () => editor.locator(":scope > p").allTextContents();
    const assertSelected = async count => {
      await page.waitForFunction(count => document.querySelectorAll(".inline-editor__block-selected").length === count, count);
      assert.equal(await selected.count(), count);
      assert.equal(await page.getByRole("toolbar").count(), 0, "Whole-block selection must not show an inline formatting bubble");
      const frames = await selected.evaluateAll(nodes => nodes.map(node => {
        const s = getComputedStyle(node);
        return [s.borderTopWidth, s.borderRightWidth, s.borderBottomWidth, s.borderLeftWidth, s.outlineWidth, s.boxShadow];
      }));
      assert(frames.every(frame => frame.slice(0, 5).every(value => value === "0px") && frame[5] === "none"), `Selected blocks must stay frameless: ${JSON.stringify(frames)}`);
      assert(await selected.evaluateAll(nodes => nodes.every(node => getComputedStyle(node, "::selection").color === getComputedStyle(node).color)), "Hidden native selection must preserve readable foreground text");
    };
    await editor.locator("p").nth(1).click();
    await editor.press("Escape");
    await assertSelected(1);
    assert.equal(await selected.textContent(), "Второй", "Immediate Escape after a native click must select the clicked paragraph");
    await editor.press("Shift+ArrowDown");
    await assertSelected(2);
    await editor.press("Shift+ArrowUp");
    await assertSelected(1);
    await editor.press("Shift+ArrowDown");
    await page.waitForTimeout(900);
    assert.equal(await page.evaluate(() => window.inlineTest.saves.length), 0, "Block selection alone must not save");
    await assertSelected(2);
    const beforeMove = await editor.evaluate(el => el.editor.state.selection.toJSON());
    await editor.press("ControlOrMeta+Shift+ArrowUp");
    assert.deepEqual(await texts(), ["Второй", "Третий", "Первый", "Четвёртый"], JSON.stringify({ beforeMove, afterMove: await editor.evaluate(el => el.editor.state.selection.toJSON()) }));
    await assertSelected(2);
    assert.equal(await editor.locator("p").first().locator("strong").textContent(), "Второй");
    await editor.press("ControlOrMeta+z");
    assert.deepEqual(await texts(), ["Первый", "Второй", "Третий", "Четвёртый"]);
    await assertSelected(2);
    await editor.press("ControlOrMeta+Shift+z");
    await editor.press("ControlOrMeta+d");
    assert.deepEqual(await texts(), ["Второй", "Третий", "Второй", "Третий", "Первый", "Четвёртый"]);
    await assertSelected(2);
    await editor.press("Backspace");
    assert.deepEqual(await texts(), ["Второй", "Третий", "Первый", "Четвёртый"]);
    await editor.press("ControlOrMeta+z");
    await assertSelected(2);
    await editor.press("ControlOrMeta+z");
    await editor.press("ControlOrMeta+z");
    assert.deepEqual(await texts(), ["Первый", "Второй", "Третий", "Четвёртый"]);
    await assertSelected(2);
    await editor.press("ControlOrMeta+/");
    const menu = page.getByRole("dialog", { name: "Действия текстового блока", exact: true });
    await menu.waitFor();
    assert.equal(await menu.getByRole("button", { name: "Дублировать блоки", exact: true }).count(), 1);
    assert.equal(await menu.getByRole("button", { name: "Переместить вниз", exact: true }).isEnabled(), true);
    await menu.getByRole("button", { name: "Дублировать блоки", exact: true }).click();
    assert.deepEqual(await texts(), ["Первый", "Второй", "Третий", "Второй", "Третий", "Четвёртый"]);
    await editor.press("ControlOrMeta+z");
    await assertSelected(2);
    const copied = await editor.evaluate(el => {
      const clipboardData = new DataTransfer();
      el.dispatchEvent(new ClipboardEvent("copy", { clipboardData, bubbles: true, cancelable: true }));
      return { html: clipboardData.getData("text/html"), text: clipboardData.getData("text/plain") };
    });
    assert.equal(copied.text, "Второй\n\nТретий");
    assert(copied.html.includes("<strong>Второй</strong>"), "Copying a group must preserve marks");
    if (width >= 1024) {
      await editor.locator("p").nth(1).hover();
      const grip = page.getByRole("button", { name: "Переместить блок или открыть меню", exact: true });
      await grip.waitFor();
      await grip.dragTo(editor.locator("p").first(), { targetPosition: { x: 20, y: 1 } });
      assert.deepEqual(await texts(), ["Второй", "Третий", "Первый", "Четвёртый"], "Dragging a selected block must move the complete group");
      await assertSelected(2);
      await editor.press("ControlOrMeta+z");
      assert.deepEqual(await texts(), ["Первый", "Второй", "Третий", "Четвёртый"]);
      await assertSelected(2);
      await editor.press("ControlOrMeta+Shift+z");
      assert.deepEqual(await texts(), ["Второй", "Третий", "Первый", "Четвёртый"]);
      await assertSelected(2);
      await editor.press("ControlOrMeta+z");
      await editor.locator("p").nth(1).hover();
      await grip.waitFor();
      const handle = await grip.boundingBox();
      const savedBeforeCancel = await page.evaluate(() => window.inlineTest.saves.length);
      await page.mouse.move(handle.x + 24, handle.y + 24);
      await page.mouse.down();
      await page.mouse.move(handle.x + 80, handle.y + 50, { steps: 10 });
      await page.keyboard.press("Escape");
      await page.mouse.up();
      await page.waitForTimeout(900);
      assert.deepEqual(await texts(), ["Первый", "Второй", "Третий", "Четвёртый"]);
      assert.equal(await editor.evaluate(el => el.editor.view.dragging), null, "Cancelled group drag must clear the pending native drag");
      assert.equal(await page.locator(".inline-editor__drag-preview").count(), 0);
      assert.equal(await page.evaluate(() => window.inlineTest.saves.length), savedBeforeCancel, "Cancelling group drag must not save");
      await assertSelected(2);
    }
    await editor.press("Enter");
    assert.equal(await editor.evaluate(el => el.editor.state.selection.$from.parent.textContent), "Третий");
    await editor.press("Escape");
    await assertSelected(1);
    await editor.press("Escape");
    assert.equal(await selected.count(), 0);
    // Cmd/Ctrl+A selects the current paragraph first, then the whole document.
    await editor.press("ControlOrMeta+a");
    assert.equal(await editor.evaluate(el => el.editor.state.doc.textBetween(el.editor.state.selection.from, el.editor.state.selection.to)), "Третий");
    await editor.press("ControlOrMeta+a");
    await editor.press("Escape");
    await assertSelected(4);
    await editor.press("Delete");
    assert.deepEqual(await texts(), [""]);
    await editor.press("ControlOrMeta+z");
    await assertSelected(4);
    assert.deepEqual(await texts(), ["Первый", "Второй", "Третий", "Четвёртый"]);
    await editor.pressSequentially("Замена");
    assert.deepEqual(await texts(), ["Замена"], "Typing over a group must replace the entire selected range");
    await editor.press("ControlOrMeta+z");
    assert.deepEqual(await texts(), ["Первый", "Второй", "Третий", "Четвёртый"]);
    await assertSelected(4);
    await page.screenshot({ path: `/tmp/rollapp-block-selection-${width}-${height}.png` });
    const geometry = await page.evaluate(() => ({ width: document.documentElement.scrollWidth, viewport: innerWidth }));
    assert(geometry.width <= geometry.viewport + 1, "Block selection must not cause horizontal overflow");
    await editor.press("Enter");
    await editor.pressSequentially("Начало ");
    await editor.press("ControlOrMeta+s");
    await page.waitForFunction(() => window.inlineTest.saved?.includes("Начало Четвёртый"));
    const saved = await page.evaluate(() => window.inlineTest.saved);
    await page.addInitScript(value => { window.inlineFixtureSource = value; }, saved);
    await page.reload();
    await editor.locator("p").last().waitFor();
    assert.equal(await editor.locator("p").last().textContent(), "Начало Четвёртый");
    assert.equal(await page.evaluate(() => window.inlineTest.saves.length), 0, "Reload must not save a document");
    assert.deepEqual(errors, []);
    await page.close();
    console.log(`PASS ${width}×${height}: block selection, staged select-all, group movement/duplication/deletion, contextual actions, undo/redo, immediate typing and saved reload`);
  }
  for (const width of [390, 1440]) {
    const page = await browser.newPage({ viewport: { width, height: 400 } });
    const errors = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.route("**/api/**", route => { errors.push("Unexpected API request"); return route.abort(); });
    await page.addInitScript(() => { window.inlineFixtureSource = "- [x] Первый\n- [ ] Второй\n- [ ] Третий\n\nПосле"; });
    await page.goto(`${origin}/__text-edit?block-selection=1`);
    const editor = page.getByRole("textbox", { name: "О себе", exact: true });
    const selected = editor.locator(".inline-editor__block-selected");
    const pause = () => editor.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    await editor.locator("li p").nth(1).click();
    await pause();
    await editor.press("Escape");
    await editor.press("Shift+ArrowDown");
    assert.equal(await selected.count(), 2);
    await editor.press("Tab");
    assert.equal(await editor.locator('ul[data-type="taskList"] > li > div > ul > li').count(), 2);
    assert.equal(await selected.count(), 2, "Nesting preserves group selection");
    await editor.press("Shift+Tab");
    assert.equal(await editor.locator('ul[data-type="taskList"] > li').count(), 3);
    assert.equal(await editor.getByRole("checkbox").first().isChecked(), true);
    assert.equal(await selected.count(), 2);
    await editor.locator("li p").first().click({ modifiers: ["Shift"] });
    assert.equal(await selected.count(), 2, "Shift-click extends from the original anchor to the clicked block");
    assert.deepEqual(await selected.locator("p").allTextContents(), ["Первый", "Второй"]);
    const clipboard = await editor.evaluate(el => {
      const clipboardData = new DataTransfer();
      el.dispatchEvent(new ClipboardEvent("cut", { clipboardData, bubbles: true, cancelable: true }));
      return { html: clipboardData.getData("text/html"), text: clipboardData.getData("text/plain") };
    });
    assert(clipboard.text.includes("Первый") && clipboard.text.includes("Второй"));
    assert.equal(await editor.locator("li").count(), 1);
    assert.equal(await editor.locator(":scope > p").last().textContent(), "После");
    await editor.press("ControlOrMeta+z");
    assert.equal(await editor.locator("li").count(), 3);
    assert.equal(await selected.count(), 2, "Undo of cut restores the group selection");
    await editor.press("ControlOrMeta+s");
    await page.waitForTimeout(1000);
    assert.deepEqual(errors, []);
    await page.close();
    console.log(`PASS ${width}×400: nested group Tab/Shift+Tab, Shift-click, checklist state, clipboard cut and Undo`);
  }
  for (const width of [390, 1440]) {
    const page = await browser.newPage({ viewport: { width, height: 400 } });
    const errors = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.route("**/api/**", route => { errors.push("Unexpected API request"); return route.abort(); });
    await page.goto(`${origin}/__text-edit?long=1`);
    const editor = page.getByRole("textbox", { name: "О себе", exact: true });
    await editor.locator("p").nth(12).click();
    await editor.press("Escape");
    const selected = editor.locator(".inline-editor__block-selected");
    assert((await selected.textContent()).startsWith("Блок 13:"), "Escape deep in a document selects the clicked block");
    const box = await selected.boundingBox();
    assert(box.y >= 0 && box.y + box.height <= 401, "Block selection must keep its text in the viewport");
    await editor.press("Shift+ArrowDown");
    assert.equal(await selected.count(), 2);
    await editor.press("Enter");
    assert((await editor.evaluate(el => el.editor.state.selection.$from.parent.textContent)).startsWith("Блок 14:"));
    await page.waitForTimeout(900);
    assert.equal(await page.evaluate(() => window.inlineTest.saves.length), 0);
    assert.deepEqual(errors, []);
    await page.close();
    console.log(`PASS ${width}×400: deep document block selection stays visible and does not save`);
  }
}
