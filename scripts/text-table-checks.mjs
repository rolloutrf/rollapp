import assert from 'node:assert/strict';
import { IDENTITY_QUESTION_TITLES } from '../shared/identity-questions.js';
import { identityFourQuestionsSchema } from '../server/identity-content-schema.js';

const source = 'До\n\n| A | B |\n| --- | --- |\n| C | D |\n\nПосле';
export async function checkTextTables(browser, origin) {
  for (const [width,height] of [[320,844],[390,844],[390,400],[768,844],[820,844],[1024,844],[1440,844],[1920,844]]) {
    const page = await browser.newPage({viewport:{width,height}}), errors = [];
    page.setDefaultTimeout(20000);
    page.on('pageerror',error=>errors.push(error.message));
    await page.route('**/api/**',route=>{errors.push('Unexpected API request');return route.abort();});
    const url = (value, suffix='') => `${origin}/__text-edit?source=${encodeURIComponent(value)}${suffix}`;
    await page.goto(url(source));
    const editor = page.getByRole('textbox',{name:'О себе',exact:true});
    const table = editor.locator('table');
    await table.waitFor();
    await page.evaluate(()=>document.fonts.ready);
    const json = () => editor.evaluate(el=>el.editor.getJSON());
    const initial = await json();
    const bodyStyle=await table.locator('td p').first().evaluate(el=>{const s=getComputedStyle(el);return [s.fontFamily,s.fontSize,s.lineHeight,s.fontWeight];});
    assert(bodyStyle[0].includes('Geist')); assert.deepEqual(bodyStyle.slice(1),['18px','28px','400']);
    assert.equal(await table.locator('th p').first().evaluate(el=>getComputedStyle(el).fontWeight),'600');
    const menu = page.getByRole('dialog',{name:'Действия текстового блока',exact:true});
    const open = async () => {
      await editor.press('ControlOrMeta+/');
      await menu.getByRole('group',{name:'Действия таблицы',exact:true}).waitFor();
      assert.equal(await page.getByRole('toolbar').count(),0,'Table actions must replace the formatting bubble');
    };
    const run = async label => { await open(); await menu.getByRole('button',{name:label,exact:true}).click(); await menu.waitFor({state:'hidden'}); };
    const restore = async () => { await editor.press('ControlOrMeta+z'); assert.deepEqual(await json(),initial); };
    for (const [label,rows,cols] of [['Добавить строку выше',3,2],['Добавить строку ниже',3,2],['Добавить столбец слева',2,3],['Добавить столбец справа',2,3]]) {
      await table.locator('td').first().click();
      await run(label);
      assert.equal(await table.locator('tr').count(),rows);
      assert.equal(await table.locator('td,th').count(),rows*cols);
      assert.equal(await table.textContent(),'ABCD');
      await restore();
    }
    for (const [label,headers] of [['Строка заголовков',0],['Столбец заголовков',3]]) {
      await table.locator('td').first().click(); await run(label);
      assert.equal(await table.locator('th').count(),headers);
      await restore();
    }
    await table.locator('td').first().click(); await run('Выделить строку');
    assert.equal(await table.locator('.selectedCell').count(),2);
    assert.equal(await editor.evaluate(el=>el.editor.state.selection.toJSON().type),'cell');
    assert.equal(await page.getByRole('toolbar').count(),0,'Whole-cell selection must not obscure another row with a text bubble');
    await open(); await menu.getByRole('button',{name:'Жирный',exact:true}).click(); await menu.waitFor({state:'hidden'});
    assert.equal(await table.locator('td strong').count(),2);
    await editor.press('ControlOrMeta+z');
    assert.deepEqual(await json(),initial);
    await table.locator('td').first().click(); await run('Выделить столбец');
    await open(); await menu.getByRole('button',{name:'Цвет текста и фона',exact:true}).click();
    const palette=page.getByRole('dialog',{name:'Цвет текста и фона',exact:true});
    await palette.getByRole('radio',{name:'Цвет текста: Красный',exact:true}).click();
    assert.equal(await table.locator('[data-inline-color="red"]').count(),2);
    assert.equal(await table.locator('tr').first().locator('th').nth(1).locator('[data-inline-color]').count(),0,'Column formatting must preserve neighbouring cells');
    await open(); await menu.getByRole('button',{name:'Цвет текста и фона',exact:true}).click();
    assert.equal(await palette.getByRole('radio',{name:'Цвет текста: Красный',exact:true}).getAttribute('aria-checked'),'true','The palette must inspect selected cell ranges, not intervening neighbours');
    await palette.getByRole('button',{name:'Закрыть',exact:true}).click();
    await editor.press('ControlOrMeta+z'); assert.deepEqual(await json(),initial);
    await table.locator('td').first().click(); await run('Выделить строку');
    await table.locator('th').nth(1).click({modifiers:['Shift']});
    assert.equal(await table.locator('.selectedCell').count(),4,'Shift-click must extend the rectangular cell selection');
    await run('Объединить ячейки');
    assert.equal(await table.locator('td,th').count(),1);
    assert.equal(await table.textContent(),'A','Merge keeps the top-left cell content');
    assert.equal(await table.locator('th').getAttribute('rowspan'),'2');
    assert.equal(await table.locator('th').getAttribute('colspan'),'2');
    const merged = await json();
    await editor.press('ControlOrMeta+s');
    await page.locator('[data-save-status="saved"]').waitFor();
    const mergedSource=await page.evaluate(()=>window.inlineTest.saved);
    assert(mergedSource.includes('data-inline-table'));
    await page.goto(url(mergedSource)); await table.waitFor();
    assert.deepEqual(await json(),merged,'Spanning cells must survive actual save and reload');
    assert.equal(await page.evaluate(()=>window.inlineTest.saves.length),0);
    await table.locator('th').click(); await run('Разделить ячейку');
    assert.equal(await table.locator('td,th').count(),4);
    assert.equal(await table.textContent(),'A');
    await editor.press('ControlOrMeta+z'); assert.deepEqual(await json(),merged);
    await page.goto(url(source)); await table.waitFor();
    for (const [label,expected] of [['Очистить ячейки','ABD'],['Удалить строку','AB'],['Удалить столбец','BD'],['Удалить таблицу',null]]) {
      await table.locator('td').first().click(); await run(label);
      if (expected===null) assert.equal(await table.count(),0); else assert.equal(await table.textContent(),expected);
      assert.deepEqual(await editor.locator(':scope > p').allTextContents(),['До','После']);
      await restore();
    }
    await table.locator('td').last().click();
    await editor.press('Tab'); await editor.pressSequentially('Новая строка');
    assert.equal(await table.locator('tr').count(),3);
    assert.equal(await table.locator('tr').last().locator('td,th').first().textContent(),'Новая строка');
    await editor.press('ControlOrMeta+z'); assert.equal(await table.locator('tr').count(),3);
    await restore();
    await table.locator('td').first().click(); await run('Столбец заголовков');
    await table.locator('th').first().click();
    await editor.press(process.platform==='darwin'?'Meta+ArrowRight':'End');
    await editor.press('Enter'); await editor.pressSequentially('Второй абзац');
    assert.equal(await table.locator('th').first().locator('p').count(),2);
    await editor.press('ControlOrMeta+s'); await page.locator('[data-save-status="saved"]').waitFor();
    const paragraphs=await json(), paragraphSource=await page.evaluate(()=>window.inlineTest.saved);
    await page.goto(url(paragraphSource)); await table.waitFor();
    assert.deepEqual(await json(),paragraphs,'Enter inside a cell must preserve separate paragraphs');
    const beforeResize=await table.locator('th').first().boundingBox();
    await page.mouse.move(beforeResize.x+beforeResize.width-2,beforeResize.y+beforeResize.height/2);
    await page.waitForFunction(()=>document.querySelector('.column-resize-handle'));
    await page.mouse.down();
    await page.mouse.move(width-24,beforeResize.y+beforeResize.height/2,{steps:10});
    await page.mouse.up();
    const resized=await json();
    const resizedTable=resized.content.find(node=>node.type==='table');
    assert(resizedTable.content[0].content[0].attrs.colwidth?.[0]>beforeResize.width+20,'Dragging the column boundary must persist an increased width');
    assert(await editor.evaluate(el=>{const wrapper=el.querySelector('.tableWrapper');return wrapper.scrollWidth> wrapper.clientWidth+1 && document.documentElement.scrollWidth<=innerWidth+1;}),'A wide table must scroll inside its wrapper');
    await editor.press('ControlOrMeta+z'); assert.deepEqual(await json(),paragraphs);
    await editor.press('ControlOrMeta+Shift+z'); assert.deepEqual(await json(),resized);
    await editor.press('ControlOrMeta+s'); await page.locator('[data-save-status="saved"]').waitFor();
    const stored=await page.evaluate(()=>window.inlineTest.saved);
    await page.goto(url(stored)); await table.waitFor(); assert.deepEqual(await json(),resized);
    await table.locator('th').first().click(); await open();
    if (width===390 && height===400) {
      await page.evaluate(()=>{
        Object.defineProperty(visualViewport,'height',{configurable:true,value:220}); Object.defineProperty(visualViewport,'offsetTop',{configurable:true,value:96});
        visualViewport.dispatchEvent(new Event('resize')); visualViewport.dispatchEvent(new Event('scroll'));
      });
      await page.waitForFunction(()=>{const r=document.querySelector('.inline-editor__block-menu')?.getBoundingClientRect();return r && r.top>=111 && r.bottom<=301;});
    }
    await menu.getByRole('button',{name:'Удалить таблицу',exact:true}).scrollIntoViewIfNeeded();
    const warning=await menu.evaluate(el=>{
      const probe=document.createElement('span'); probe.style.color='var(--destructive)'; el.append(probe); const expected=getComputedStyle(probe).color; probe.remove();
      return [...el.querySelectorAll('button')].filter(button=>/^(Удалить (строку|столбец|таблицу)|Очистить ячейки)$/.test(button.textContent)).every(button=>getComputedStyle(button).color===expected);
    });
    assert(warning,'Table deletion and clearing must keep the destructive warning color');
    const menuRect=await menu.boundingBox();
    assert(menuRect.x>=0 && menuRect.x+menuRect.width<=width+1 && menuRect.y>=0 && menuRect.y+menuRect.height<=height+1);
    await menu.press('Escape');
    await menu.waitFor({state:'hidden'});
    if(width===390 || width===1440) await page.screenshot({path:`/tmp/rollapp-table-${width}-${height}.png`});
    await page.goto(url(stored,'&public=1'));
    const publicTable=page.getByRole('textbox',{name:'Опубликованный текст',exact:true});
    await publicTable.locator('table').waitFor();
    assert.equal(await page.locator('[contenteditable="true"]').count(),0);
    assert.equal(await page.getByRole('toolbar').count(),0);
    assert.equal(await publicTable.locator('th').first().locator('p').count(),2);
    assert.equal(await page.evaluate(()=>window.inlineTest.saves.length),0);
    assert.equal(await publicTable.locator('col').first().evaluate(el=>parseInt(el.style.width)),resizedTable.content[0].content[0].attrs.colwidth[0]);
    assert(!(await page.locator('main').textContent()).includes('<table'));
    const rhythm=await publicTable.evaluate(el=>{
      const first=el.querySelector(':scope > p').getBoundingClientRect(), table=el.querySelector('table').getBoundingClientRect();
      return {gap:table.top-first.bottom,flow:parseFloat(getComputedStyle(el).fontSize)*1.25};
    });
    assert(Math.abs(rhythm.gap-rhythm.flow)<=1,'Reading must keep the same table-to-prose rhythm as editing');
    await page.goto(url(source,'&public=1'));
    await publicTable.locator('table').waitFor(); assert.equal(await publicTable.locator('td,th').count(),4);
    await page.goto(url('```md\n| A | B |\n| --- | --- |\n<table data-inline-table="true">literal</table>\n```','&public=1'));
    await publicTable.locator('pre code').waitFor();
    assert.equal(await publicTable.locator('table').count(),0,'Table syntax inside a code fence must remain literal in public reading');
    const questions={questions:IDENTITY_QUESTION_TITLES.map((title,index)=>({title,paragraphs:[index===0?stored:`Ответ ${index}`]}))};
    await page.goto(`${origin}/__text-edit?four=1&questions=${encodeURIComponent(JSON.stringify(questions))}`);
    const four=page.getByRole('textbox',{name:'Ответы на четыре вопроса',exact:true});
    await four.locator('table th').first().click(); await four.press('ControlOrMeta+/');
    await menu.getByRole('button',{name:'Добавить строку ниже',exact:true}).click();
    await four.press('ControlOrMeta+s'); await page.locator('[data-save-status="saved"]').waitFor();
    const saved=await page.evaluate(()=>window.inlineTest.saved);
    assert.deepEqual(identityFourQuestionsSchema.parse(saved),saved);
    assert.deepEqual(saved.questions.slice(1),questions.questions.slice(1));
    assert.equal(await four.locator('[data-question-index]').count(),4);
    await page.goto(url(stored,'&error=1'));
    await table.locator('th p').first().fill('Черновик ячейки');
    const draft=await json();
    await editor.press('ControlOrMeta+s'); await page.locator('[data-save-status="error"]').waitFor();
    page.once('dialog',dialog=>dialog.accept()); await page.reload();
    await page.locator('[data-save-status="error"]').waitFor();
    assert.deepEqual(await json(),draft,'A failed rich table save must restore all cell structure and widths');
    assert.equal(await page.evaluate(()=>window.inlineTest.saves.length),0);
    await page.evaluate(()=>{window.inlineTest.fail=false;});
    await page.getByRole('button',{name:'Повторить сохранение',exact:true}).click();
    await page.locator('[data-save-status="saved"]').waitFor(); assert.deepEqual(await json(),draft);
    await page.goto(url(source,'&readonly=1'));
    await table.waitFor(); assert.equal(await page.locator('[contenteditable="true"]').count(),0);
    assert.equal(await page.getByRole('button',{name:'Добавить строку ниже',exact:true}).count(),0);
    const readCell=await table.locator('th').first().boundingBox();
    await page.mouse.move(readCell.x+readCell.width-2,readCell.y+readCell.height/2);
    assert.equal(await page.locator('.column-resize-handle').count(),0);
    await page.goto(url(source,'&readonly=1&access=1'));
    await table.waitFor();
    await page.getByRole('button',{name:'Разрешить редактирование',exact:true}).click();
    const accessInitial=await json(), accessCell=await table.locator('th').first().boundingBox();
    await page.mouse.move(accessCell.x+accessCell.width-2,accessCell.y+accessCell.height/2);
    await page.waitForFunction(()=>document.querySelector('.column-resize-handle'));
    await page.mouse.down(); await page.mouse.move(accessCell.x+accessCell.width+40,accessCell.y+accessCell.height/2,{steps:5});
    await page.getByRole('button',{name:'Только чтение',exact:true}).focus();
    await page.keyboard.press('Space');
    await page.waitForFunction(()=>document.querySelector('[aria-label="О себе"][role="textbox"]').contentEditable==='false');
    await page.mouse.up();
    assert.deepEqual(await json(),accessInitial,'Revoking access during a resize must cancel its pending write');
    assert.equal(await page.locator('.column-resize-handle').count(),0);
    await page.waitForTimeout(850);
    assert.equal(await page.evaluate(()=>window.inlineTest.saves.length),0);
    await page.getByRole('button',{name:'Разрешить редактирование',exact:true}).click();
    await table.locator('td').first().click(); await open();
    assert.equal(await menu.getByRole('button',{name:'Добавить строку ниже',exact:true}).isEnabled(),true);
    await menu.press('Escape');
    assert.deepEqual(errors,[]);
    console.log(`PASS table editing ${width}×${height}: row/column actions, native cell selection/styles/colors, merge/split, Enter/Tab/Undo, resize/scroll, exact save/reload/draft, public read, four-answer guards and access changes during resize`);
    await page.close();
  }
}
